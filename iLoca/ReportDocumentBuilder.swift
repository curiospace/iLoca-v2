import AppKit

/// Composes the report's content as an NSAttributedString (fed to ReportPDFRenderer).
enum ReportDocumentBuilder {

    struct Input {
        let block: CityBlock
        let metrics: BlockMetrics
        let confidence: ConfidenceAssessment
        let filtersSummary: String
        let premises: [BusinessRecord]?
        let narrative: String
        let aiProvider: String
        let censusYear: Int
        let freshness: String
        let datasets: [DatasetInfo]
        let parking: ParkingSummary
        let parkingNote: String
    }

    static func buildAttributedString(_ input: Input) -> NSAttributedString {
        let result = NSMutableAttributedString()

        func addTitle(_ text: String) {
            result.append(NSAttributedString(string: text + "\n", attributes: [
                .font: NSFont.boldSystemFont(ofSize: 22),
                .foregroundColor: NSColor.black
            ]))
        }
        func addHeading(_ text: String) {
            let spacer = NSMutableParagraphStyle()
            spacer.paragraphSpacingBefore = 14
            result.append(NSAttributedString(string: text + "\n", attributes: [
                .font: NSFont.boldSystemFont(ofSize: 14),
                .foregroundColor: NSColor.black,
                .paragraphStyle: spacer
            ]))
        }
        func addBody(_ text: String, size: CGFloat = 11, color: NSColor = .black) {
            let paragraph = NSMutableParagraphStyle()
            paragraph.paragraphSpacing = 4
            paragraph.lineSpacing = 2
            result.append(NSAttributedString(string: text + "\n", attributes: [
                .font: NSFont.systemFont(ofSize: size),
                .foregroundColor: color,
                .paragraphStyle: paragraph
            ]))
        }
        func addRow(_ label: String, _ value: String) {
            let bold = NSMutableAttributedString(string: "\(label): ", attributes: [
                .font: NSFont.boldSystemFont(ofSize: 11),
                .foregroundColor: NSColor.black
            ])
            let paragraph = NSMutableParagraphStyle()
            paragraph.paragraphSpacing = 3
            bold.append(NSAttributedString(string: value + "\n", attributes: [
                .font: NSFont.systemFont(ofSize: 11),
                .foregroundColor: NSColor.black,
                .paragraphStyle: paragraph
            ]))
            result.append(bold)
        }

        let block = input.block
        let score = input.metrics.score

        addTitle("iLoca Location Report")
        addBody("Block \(block.blockId) · \(block.area)")
        addBody("Generated \(Date().formatted(date: .abbreviated, time: .shortened)) · \(input.freshness)", size: 9, color: .darkGray)

        addHeading("AI Analysis")
        addBody("AI-generated by \(input.aiProvider). Decision support only. This is not financial, legal or planning advice, and it doesn't guarantee business success.", size: 9, color: .darkGray)
        addBody(input.narrative)

        addHeading("Opportunity Score")
        addRow("Score", "\(score.value) / 100 (\(score.tier.rawValue))")
        for c in score.components {
            let value = c.value.map { "\(Int($0.rounded()))/100 × \(Int((c.appliedWeight * 100).rounded()))%" } ?? "not available (excluded)"
            addRow(c.kind.rawValue, "\(value). \(c.detail)")
        }

        addHeading("Confidence")
        addRow("Level", "\(input.confidence.level.rawValue) (\(input.confidence.points)/100). \(input.confidence.summary)")
        for f in input.confidence.factors {
            addRow(f.name, "\(f.points)/\(f.maxPoints). \(f.detail)")
        }

        addHeading("Key Stats")
        addRow("Foot traffic", input.metrics.footfall.map { "\(Int($0.rounded())) people/hr in the selected window" } ?? "No pedestrian sensor nearby, so unknown")
        addRow("Vacancy rate", String(format: "%.1f%% (%d of %d premises)", block.vacancyRatePct, block.vacantPremises, block.totalPremises))
        addRow("Active businesses", "\(block.activeEstablishments) (FnB \(block.fnbCount), Retail \(block.retailCount), Services \(block.servicesCount))")
        addRow("Competitors in radius", "\(input.metrics.competitorsInRadius)")

        addHeading("Parking (context, not scored)")
        addRow("Public car parks in radius", "\(input.parking.carParks.count) (\(input.parking.publicSpaces) spaces)")
        addRow("Private spaces in block", "\(input.parking.privateSpacesInBlock)")
        addRow("On-street sensor bays", input.parking.bayCount > 0 ? "\(input.parking.freeBays) of \(input.parking.bayCount) free \(input.parkingNote)" : "None with sensors in radius")
        for item in input.parking.carParks.prefix(5) {
            addBody("• \(item.carPark.address): \(item.carPark.spaces) spaces, \(Int(item.distance)) m", size: 10)
        }

        addHeading("Search Criteria Applied")
        for line in input.filtersSummary.split(separator: "\n") {
            let parts = line.split(separator: ":", maxSplits: 1)
            if parts.count == 2 {
                addRow(String(parts[0]), String(parts[1]).trimmingCharacters(in: .whitespaces))
            } else {
                addBody(String(line))
            }
        }

        addHeading("Industry Mix")
        if block.industryMix.isEmpty {
            addBody("No industry breakdown available for this block.")
        } else {
            for (name, count) in block.industryMix.sorted(by: { $0.value > $1.value }) {
                addBody("• \(name): \(count)")
            }
        }

        if let premises = input.premises {
            let businesses = premises.filter { !$0.isVacant }
            addHeading("Businesses (\(businesses.count) total\(businesses.count > 60 ? ", first 60 shown" : ""))")
            for biz in businesses.prefix(60) {
                addBody("• \(biz.name): \(biz.industry), \(biz.address)")
            }
            let vacancies = premises.filter(\.isVacant)
            if !vacancies.isEmpty {
                addHeading("Vacant Premises (\(vacancies.count))")
                for v in vacancies.prefix(40) { addBody("• \(v.address)") }
            }
        }

        addHeading("Data Sources")
        for info in input.datasets {
            addBody("• \(info.dataset.title), City of Melbourne Open Data. Portal updated \(info.modified?.formatted(date: .abbreviated, time: .omitted) ?? "n/a"). Licence: \(info.license ?? "see portal").", size: 10)
        }

        addHeading("Limitations")
        addBody("Business and vacancy figures come from the \(input.censusYear) CLUE census. Foot traffic is the average from the nearest City of Melbourne pedestrian sensor within \(Int(OpenDataClient.sensorMatchRadius)) m. Blocks without one have no foot-traffic reading, and their score uses the remaining factors. Competitor radius uses block centres. On-street parking counts sensor-fitted bays only. iLoca has no rent, lease, public transport, demographic or zoning data. A location insight doesn't confirm a premises is permitted for a particular use.", size: 10)

        return result
    }
}
